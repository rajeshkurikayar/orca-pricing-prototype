function genWindSeries(
  startIso: string,
  hours: number,
  capacityMw: number,
  gapAt?: { fromHour: number; toHour: number },
): { points: TimeSeries['points']; missingCount: number } {
  const points: TimeSeries['points'] = []
  const start = new Date(startIso).getTime()
  let missingCount = 0
  for (let h = 0; h < hours; h++) {
    const ts = new Date(start + h * 3_600_000).toISOString()
    const isGap = gapAt && h >= gapAt.fromHour && h < gapAt.toHour
    if (isGap) {
      missingCount++
      continue
    }
    const dailyCycle = Math.sin((h % 24) / 24 * Math.PI * 2 - Math.PI / 2) * 0.25 + 0.55
    const noise = Math.sin(h * 1.7) * 0.15 + Math.sin(h * 0.31) * 0.1
    const factor = Math.max(0.02, Math.min(1, dailyCycle + noise))
    points.push({
      timestampUtc: ts,
      value: Math.round(factor * capacityMw * 100) / 100,
      qualityFlag: 'GOOD',
    })
  }
  return { points, missingCount }
}

